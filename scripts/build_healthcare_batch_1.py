def normalize_string(s: str) -> str:
    if not s:
        return ""
    return re.sub(r"[^a-zA-Z0-9]", "", s).lower()


def clean_phone(phone: str) -> str:
    if not phone:
        return ""
    digits = re.sub(r"\D", "", phone)
    if digits.startswith("91") and len(digits) == 12:
        return digits[2:]
    return digits[-10:] if len(digits) >= 10 else digits


def deduplicate_targets(targets: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    seen_domains: Set[str] = set()
    seen_phones: Set[str] = set()
    seen_names: Set[str] = set()

    unique: List[Dict[str, Any]] = []

    for t in targets:
        domain = ""
        if t.get("website_url"):
            domain = normalize_string(
                re.sub(r"^https?://(www\.)?", "", t["website_url"]).split("/")[0]
            )

        phone = clean_phone(t.get("phone") or "")
        name_city = f"{normalize_string(t.get('business_name') or '')}_{normalize_string(t.get('city') or '')}"

        if domain and domain in seen_domains:
            continue
        if phone and len(phone) == 10 and phone in seen_phones:
            continue
        if name_city in seen_names:
            continue

        if domain:
            seen_domains.add(domain)
        if phone and len(phone) == 10:
            seen_phones.add(phone)
        seen_names.add(name_city)

        unique.append(t)

    return unique


